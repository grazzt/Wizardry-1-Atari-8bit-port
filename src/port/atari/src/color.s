; Colour for SYSTEM.STARTUP's hi-res pictures (the title), in the start-up
; overlay at $6000: loaded at boot, used only by program 0, and free for the
; game's stack afterwards.
;
; The Apple makes colour from dot patterns: a lit dot next to a lit dot is
; white; a lone lit dot is purple or green (palette bit 0) or blue or orange
; (palette bit 1), by even or odd column. The Apple bytes are kept in a shadow
; of the bitmap ($2000 higher), and changed 2-byte groups are redrawn in ANTIC
; mode E (160 pixels, 4 colours): one Atari pixel per Apple dot pair, 7 pairs
; per group becoming 8 pixels (the 7th doubled), as in the monochrome mapping.
;
; Mode E shows black, white and two colours. Each band of 8 lines gets its two
; most frequent hues, loaded by a display-list interrupt at the end of the
; band before; other hues use the nearest chosen one. (Per-line interrupts
; would nest: mode E lines are one scanline tall.) Tables generated by build.py
; (color_tables.inc) turn an Apple byte and its neighbouring dots straight into
; a pattern of 4 pair classes; a translation table for the band's two hues
; (one per pair of hues, built at start) turns the pattern into the finished
; mode E byte.

SHADOW_OFS  = $20               ; shadow = bitmap address + $2000 ($4000-$5E0F)

cz_y    = $E0                   ; zero page used only here
cz_src  = $E1                   ; 2: shadow line
cz_dst  = $E3                   ; 2: bitmap line
cz_a    = $E5                   ; group bytes
cz_b    = $E6
cz_cls  = $E7                   ; 2: class table pointer
cz_tr   = $F4                   ; 2: translation table pointer
cz_tp   = $F6                   ; translation page of the band (palette 0; +1 for 1)
cz_t    = $EB
cz_g    = $EC
cz_end  = $ED
cz_band = $EE
cz_li   = $EF

dmin:       .res 192            ; dirty group range per line ($FF = clean)
dmax:       .res 192
band_c0:    .res 25             ; Atari colour for code 01 in each band
band_c1:    .res 25             ; ... and for code 10
band_ha:    .res 24             ; the hues chosen for each band (0 = none yet)
band_hb:    .res 24
cnt_lo:     .res 6              ; hue counts for the band (16-bit)
cnt_hi:     .res 6
line_n2:    .res 192            ; per-line counts of lone dots by hue (each < 256)
line_n3:    .res 192
line_n4:    .res 192
line_n5:    .res 192
map:        .res 6              ; hue -> 2-bit mode E code
hue_a:      .byte 0
hue_b:      .byte 0
dli_line:   .byte 0
; Translation table for each pair of hues (hue_a < hue_b), by (a-2)*4 + (b-2).
pair_slot:  .byte 0, 0, 1, 2,  0, 0, 3, 4,  0, 0, 0, 5,  0, 0, 0, 0
pair_a:     .byte 2, 2, 2, 3, 3, 4
pair_b:     .byte 3, 4, 5, 4, 5, 5
code:       .res 8              ; palette*4 + class -> 2-bit code (while building)

; Atari colours for hues 2-5: purple, green, blue, orange.
hue_color:  .byte 0, $0E, $68, $C8, $A8, $38
; For each hue, the others in order of similarity.
nearest:    .byte 4, 5, 3            ; purple: blue, orange, green
            .byte 4, 5, 2            ; green:  blue, orange, purple
            .byte 2, 3, 5            ; blue:   purple, green, orange
            .byte 2, 3, 4            ; orange: purple, green, blue

        .include "color_tables.inc"     ; page-aligned class tables

        .align 256
trans:  .res 12 * 256           ; translation tables: 6 hue pairs x 2 palettes

color_init:                     ; everything clean, no band colours chosen
        ldx #191
@d:     lda #$FF
        sta dmin,x
        sta dmax,x
        lda #0
        sta line_n2,x
        sta line_n3,x
        sta line_n4,x
        sta line_n5,x
        dex
        cpx #$FF
        bne @d
        ldx #23
        lda #0
@b:     sta band_ha,x
        sta band_hb,x
        dex
        bpl @b
        ldx #5                  ; the translation tables for every pair of hues
@s:     lda pair_a,x
        sta hue_a
        lda pair_b,x
        sta hue_b
        jsr build_slot
        dex
        bpl @s
        rts

; --- marking changes ------------------------------------------------------------
; Mark the group holding column A of line X dirty. Clobbers Y.
mark:   lsr a
        cmp dmin,x
        bcs @hi
        sta dmin,x
@hi:    ldy dmax,x
        cpy #$FF                ; clean
        beq @set
        cmp dmax,x
        bcc @r
@set:   sta dmax,x
@r:     rts

mark_line:                      ; whole line X; keeps X and Y
        lda #0
        sta dmin,x
        lda #19
        sta dmax,x
        rts

; Apple byte in nat0+2 to the shadow of the Atari address in nat0 (row in Y).
color_write:
        tya
        tax
        sec
        lda nat0
        sbc bm_row_lo,x
        jsr mark                ; column -> group
        lda nat0+1
        clc
        adc #SHADOW_OFS
        sta nat0+1
        ldy #0
        lda nat0+2
        sta (nat0),y
        rts

; Read the Apple byte at the shadow of nat0.
color_read:
        lda nat0+1
        clc
        adc #SHADOW_OFS
        sta nat0+1
        ldy #0
        lda (nat0),y
        rts

; --- redrawing --------------------------------------------------------------------
render_dirty:
        lda #0
        sta cz_band
@band:  lda cz_band
        asl a
        asl a
        asl a
        tax
        ldy #8
        lda #$FF
@any:   and dmin,x              ; any line with dmin <> $FF?
        inx
        dey
        bne @any
        cmp #$FF
        beq @next
        jsr render_band
@next:  inc cz_band
        lda cz_band
        cmp #24
        bne @band
        rts

render_band:
        jsr count_band
        jsr choose_hues
        ldx cz_band             ; new colours: redraw the whole band
        lda hue_a
        cmp band_ha,x
        bne @all
        lda hue_b
        cmp band_hb,x
        beq @keep
@all:   lda hue_a
        sta band_ha,x
        lda hue_b
        sta band_hb,x
        ldy hue_a
        lda hue_color,y
        sta band_c0,x
        ldy hue_b
        lda hue_color,y
        sta band_c1,x
        txa
        asl a
        asl a
        asl a
        tax
        ldy #8
@ml:    jsr mark_line
        inx
        dey
        bne @ml
@keep:  jsr build_pc
        lda #0
        sta cz_li
@line:  lda cz_band
        asl a
        asl a
        asl a
        ora cz_li
        sta cz_y
        tax
        lda dmin,x
        cmp #$FF
        beq @nl
        jsr render_line
@nl:    inc cz_li
        lda cz_li
        cmp #8
        bne @line
        rts

; Hue counts for the band: recount the band's changed lines, then add up the
; cached counts of all 8 lines.
count_band:
        lda #0
        sta cz_li
@rc:    lda cz_band
        asl a
        asl a
        asl a
        ora cz_li
        sta cz_y
        tax
        lda dmin,x
        cmp #$FF
        beq @nr
        jsr count_line
@nr:    inc cz_li
        lda cz_li
        cmp #8
        bne @rc
        ldx #5
        lda #0
@z:     sta cnt_lo,x
        sta cnt_hi,x
        dex
        bpl @z
        lda cz_band
        asl a
        asl a
        asl a
        tax
        ldy #8
@sum:   lda line_n2,x
        clc
        adc cnt_lo+2
        sta cnt_lo+2
        bcc @s3
        inc cnt_hi+2
@s3:    lda line_n3,x
        clc
        adc cnt_lo+3
        sta cnt_lo+3
        bcc @s4
        inc cnt_hi+3
@s4:    lda line_n4,x
        clc
        adc cnt_lo+4
        sta cnt_lo+4
        bcc @s5
        inc cnt_hi+4
@s5:    lda line_n5,x
        clc
        adc cnt_lo+5
        sta cnt_lo+5
        bcc @s6
        inc cnt_hi+5
@s6:    inx
        dey
        bne @sum
        rts

; Count line cz_y's lone dots by hue: a dot at offset i of byte column c is at
; an even screen column if c + i is even; palette bit 1 selects blue/orange.
cn2     = $F0                   ; zero page: the line's four counts
cn3     = $F1
cn4     = $F2
cn5     = $F3
count_line:
        jsr line_ptrs
        lda #0
        sta cn2
        sta cn3
        sta cn4
        sta cn5
        ldy #39
@byte:  lda (cz_src),y
        beq @next               ; nothing lit
        tax
        bmi @pal1
        tya
        lsr a
        bcs @odd0
        lda lone_even,x         ; palette 0, even byte column
        adc cn2                 ; (carry clear from the LSR)
        sta cn2
        lda lone_odd,x
        clc
        adc cn3
        sta cn3
        jmp @next
@odd0:  lda lone_odd,x          ; palette 0, odd byte column: offsets swap
        clc
        adc cn2
        sta cn2
        lda lone_even,x
        clc
        adc cn3
        sta cn3
        jmp @next
@pal1:  tya
        lsr a
        bcs @odd1
        lda lone_even,x
        adc cn4
        sta cn4
        lda lone_odd,x
        clc
        adc cn5
        sta cn5
        jmp @next
@odd1:  lda lone_odd,x
        clc
        adc cn4
        sta cn4
        lda lone_even,x
        clc
        adc cn5
        sta cn5
@next:  dey
        bpl @byte
        ldx cz_y
        lda cn2
        sta line_n2,x
        lda cn3
        sta line_n3,x
        lda cn4
        sta line_n4,x
        lda cn5
        sta line_n5,x
        rts

choose_hues:                    ; the two largest counts among hues 2-5
        lda #2
        sta hue_a
        ldx #3
@c1:    jsr @bigger             ; counts[x] > counts[hue_a]?
        bcc @c1n
        stx hue_a
@c1n:   inx
        cpx #6
        bne @c1
        lda #2
        ldx hue_a
        cpx #2
        bne @c2s
        lda #3
@c2s:   sta hue_b
        ldx #2
@c2:    cpx hue_a
        beq @c2n
        ldy hue_b
        lda cnt_hi,x
        cmp cnt_hi,y
        bcc @c2n
        bne @c2t
        lda cnt_lo,x
        cmp cnt_lo,y
        bcc @c2n
        beq @c2n
@c2t:   stx hue_b
@c2n:   inx
        cpx #6
        bne @c2
        lda hue_a               ; keep the pair in order: hue_a < hue_b
        cmp hue_b
        bcc @r
        ldx hue_b
        sta hue_b
        stx hue_a
@r:     rts
@bigger:                        ; carry set if counts[x] > counts[hue_a]
        ldy hue_a
        lda cnt_hi,x
        cmp cnt_hi,y
        bcc @no
        bne @yes
        lda cnt_lo,x
        cmp cnt_lo,y
        beq @no
        rts                     ; carry from the compare
@yes:   sec
        rts
@no:    clc
        rts

; Point cz_tp at the translation tables for the chosen hues, building them
; into the next cache slot if they are not there.
build_pc:                       ; cz_tp := the tables for hue_a, hue_b
        lda hue_a
        sec
        sbc #2
        asl a
        asl a
        sta cz_t
        lda hue_b
        sec
        sbc #2
        ora cz_t
        tax
        lda pair_slot,x
        asl a                   ; slot X: pages trans + 2X (palette 0), + 2X + 1
        clc
        adc #>trans
        sta cz_tp
        rts

; Build slot X's two pages: for each 4-class pattern, the mode E byte.
build_slot:
        stx cz_li
        ldx #2
@m:     jsr map_hue
        sta map,x
        inx
        cpx #6
        bne @m
        ldx #0                  ; code[palette*4 + class]
@c:     txa
        and #3
        beq @blk
        cmp #1
        beq @wht
        sta cz_t
        txa
        and #4
        lsr a
        clc
        adc cz_t
        tay
        lda map,y
        jmp @st
@blk:   lda #0
        beq @st
@wht:   lda #3
@st:    sta code,x
        inx
        cpx #8
        bne @c
        lda cz_li               ; destination page
        asl a
        clc
        adc #>trans
        sta cz_tr+1
        lda #0
        sta cz_tr
        sta cz_g                ; palette 0, then 1
@pal:   ldy #0
@p:     tya                     ; pattern: classes in bits 7-6, 5-4, 3-2, 1-0
        rol a
        rol a
        rol a
        and #3
        ora cz_g
        tax
        lda code,x
        asl a
        asl a
        sta cz_t
        tya
        lsr a
        lsr a
        lsr a
        lsr a
        and #3
        ora cz_g
        tax
        lda code,x
        ora cz_t
        asl a
        asl a
        sta cz_t
        tya
        lsr a
        lsr a
        and #3
        ora cz_g
        tax
        lda code,x
        ora cz_t
        asl a
        asl a
        sta cz_t
        tya
        and #3
        ora cz_g
        tax
        lda code,x
        ora cz_t
        sta (cz_tr),y
        iny
        bne @p
        inc cz_tr+1
        lda cz_g
        bne @done
        lda #4
        sta cz_g
        bne @pal
@done:  ldx cz_li
        rts

; A := mode E code for hue X (2-5). Keeps X.
map_hue:
        cpx hue_a
        beq @a
        cpx hue_b
        beq @b
        txa                     ; nearest of the two chosen
        sec
        sbc #2
        sta cz_t
        asl a
        adc cz_t                ; *3
        tay
        lda #3
        sta cz_g
@try:   lda nearest,y
        cmp hue_a
        beq @a
        cmp hue_b
        beq @b
        iny
        dec cz_g
        bne @try
@a:     lda #1
        rts
@b:     lda #2
        rts

line_ptrs:                      ; cz_dst / cz_src for line cz_y
        ldx cz_y
        lda bm_row_lo,x
        sta cz_dst
        sta cz_src
        lda bm_row_hi,x
        sta cz_dst+1
        clc
        adc #SHADOW_OFS
        sta cz_src+1
        rts

; Redraw the dirty groups of line cz_y, and one group either side: a dot's
; colour depends on its neighbours.
render_line:
        ldx cz_y
        lda dmax,x
        cmp #19
        bcs @e
        adc #1
@e:     sta cz_end
        lda dmin,x
        beq @s
        sec
        sbc #1
@s:     sta cz_g
        lda #$FF
        sta dmin,x
        sta dmax,x
        jsr line_ptrs
@group: lda cz_g
        asl a
        tay                     ; Y = column of byte A
        lda (cz_src),y
        sta cz_a
        iny
        lda (cz_src),y
        sta cz_b
        and #3                  ; class table page: B's first two dots
        clc
        adc #>class_a
        sta cz_cls+1
        lda cz_a                ; index: A's dots << 1 | the previous dot
        asl a
        sta cz_t
        dey
        beq @nol
        dey
        lda (cz_src),y          ; the previous byte's dot 6
        iny
        and #$40
        beq @nol
        inc cz_t
@nol:   ldy cz_t
        lda (cz_cls),y          ; pattern of pairs 0-3
        tay
        lda cz_tp               ; palette of byte A
        bit cz_a
        bpl @pa
        clc
        adc #1
@pa:    sta cz_tr+1
        lda (cz_tr),y
        sta cz_t
        lda cz_g
        asl a
        tay
        lda cz_t
        sta (cz_dst),y
        iny                     ; Y = column of byte B
        lda cz_b                ; index: B's dots | the next dot << 7
        and #$7F
        sta cz_t
        iny
        cpy #40
        bcs @nor
        lda (cz_src),y
        lsr a
        bcc @nor
        lda cz_t
        ora #$80
        sta cz_t
@nor:   ldx cz_t
        ldy class_b,x           ; pattern of pairs 4-6, pixel 7 repeating 6
        lda cz_tp
        bit cz_b
        bpl @pb
        clc
        adc #1
@pb:    sta cz_tr+1
        lda (cz_tr),y
        sta cz_t
        lda cz_g
        asl a
        tay
        iny
        lda cz_t
        sta (cz_dst),y
        inc cz_g
        lda cz_end
        cmp cz_g
        bcc @done
        jmp @group
@done:  rts

; --- display ------------------------------------------------------------------------
; Switch the graphics display list to mode E, with an interrupt on the last line
; of each band of 8 lines (and the last blank line, for band 0).
color_dl_on:
        lda #<dli_first
        sta VDSLST
        lda #>dli_first
        sta VDSLST+1
        ldx #2
        lda #$F0                ; the last blank line interrupts: colours for band 0
        sta DL_GFX,x
        ldx #0
        ldy #0                  ; line number
@l:     lda DL_GFX+3,x
        cmp #$41
        beq @done
        and #$40
        ora #$0E                ; mode E (keeps the LMS bit)
        sta cz_t
        tya
        and #7
        cmp #7
        bne @nodli
        cpy #191
        beq @nodli
        lda cz_t
        ora #$80                ; interrupt at the end of the band
        sta cz_t
@nodli: lda cz_t
        sta DL_GFX+3,x
        and #$40
        beq @n
        inx                     ; skip the LMS address
        inx
@n:     inx
        iny
        bne @l
@done:  lda #$C0
        sta NMIEN
        rts

dli_first:
        pha
        lda #$0E
        sta WSYNC
        sta COLPF2              ; code 11 = white in mode E
        lda band_c0
        sta COLPF0
        lda band_c1
        sta COLPF1
        lda #1
        sta dli_line
        lda #<dli_bands
        sta VDSLST
        lda #>dli_bands
        sta VDSLST+1
        pla
        rti

dli_bands:                      ; at the end of band n-1: colours for band n
        pha
        txa
        pha
        ldx dli_line
        lda band_c0,x
        sta WSYNC
        sta COLPF0
        lda band_c1,x
        sta COLPF1
        inx
        stx dli_line
        cpx #24
        bcc @r
        lda #<dli_first
        sta VDSLST
        lda #>dli_first
        sta VDSLST+1
@r:     pla
        tax
        pla
        rti

OVERLAY_END:                    ; (start-up stack floor)
